const {
  withDangerousMod,
  withInfoPlist,
  withStringsXml,
  AndroidConfig,
} = require('@expo/config-plugins');
const fs = require('node:fs');
const path = require('node:path');

// Per-locale display name shown under the app icon. iOS picks the locale
// based on the device language order; Android picks based on the system
// language. The `default` value is what shows when the device locale
// isn't in the list.
//
// Ported from dyarna-rn. Unlike the resident app, the names are passed in by
// app.config.ts (so the dev variant keeps its "Dev" suffix and the Arabic
// label comes from the fm.appName translation) instead of being hard-coded.
function resolveNames(config, options) {
  const en = (options && options.en) || config.name;
  const ar = (options && options.ar) || en;
  return { default: en, en, ar };
}

const SUPPORTED_LOCALES = ['en', 'ar'];

// Escape characters that have meaning inside an `InfoPlist.strings` value:
// double-quotes and backslashes. Keys in our case are ASCII so we don't
// need to do anything fancy with the key side.
function escapeStringsValue(value) {
  return value.replaceAll('\\', '\\\\').replaceAll('"', '\\"');
}

// `usage` holds optional per-locale permission strings (InfoPlist keys such as
// NSPhotoLibraryUsageDescription). They share this file because iOS reads one
// InfoPlist.strings per locale, and this plugin writes it.
function buildInfoPlistStringsContent(name, usage) {
  const escaped = escapeStringsValue(name);
  const extra = Object.entries(usage || {})
    .map(([key, value]) => `${key} = "${escapeStringsValue(value)}";\n`)
    .join('');
  // InfoPlist.strings is read in UTF-16 by default unless explicitly
  // declared. Saving as plain UTF-8 with a BOM-less header works on
  // modern iOS but the safest path is to write the file as UTF-16 LE
  // with a BOM. Easier: declare the encoding via a comment on line 1
  // — Apple's plutil reads UTF-8 fine when there's no BOM and no NULs.
  return (
    `// Generated by plugins/with-localized-app-name.js — do not edit by hand.\n` +
    `CFBundleDisplayName = "${escaped}";\n` +
    `CFBundleName = "${escaped}";\n` +
    extra
  );
}

const withIosLocalizedName = (config, NAMES, USAGE) => {
  // Tell iOS we ship localized strings + which locales to look for. Without
  // CFBundleAllowMixedLocalizations the system would only fall back to the
  // dev region; with it, an Arabic-on-an-English-phone user still gets the
  // Arabic display name.
  config = withInfoPlist(config, (cfg) => {
    cfg.modResults.CFBundleDisplayName = NAMES.default;
    cfg.modResults.CFBundleName = NAMES.default;
    cfg.modResults.CFBundleAllowMixedLocalizations = true;
    cfg.modResults.CFBundleLocalizations = SUPPORTED_LOCALES;
    return cfg;
  });

  // Write `ios/<ProjectName>/<locale>.lproj/InfoPlist.strings` for every
  // supported locale. These files have to live next to Info.plist for
  // iOS to resolve them; the project name is whatever Expo picked from
  // the slug at prebuild time.
  config = withDangerousMod(config, [
    'ios',
    async (cfg) => {
      const iosRoot = cfg.modRequest.platformProjectRoot;
      const projectName = cfg.modRequest.projectName;
      if (!projectName) return cfg;
      const targetDir = path.join(iosRoot, projectName);
      if (!fs.existsSync(targetDir)) return cfg;

      for (const locale of SUPPORTED_LOCALES) {
        const lprojDir = path.join(targetDir, `${locale}.lproj`);
        fs.mkdirSync(lprojDir, { recursive: true });
        const filePath = path.join(lprojDir, 'InfoPlist.strings');
        const content = buildInfoPlistStringsContent(NAMES[locale], USAGE[locale]);
        fs.writeFileSync(filePath, content, 'utf8');
      }
      return cfg;
    },
  ]);

  return config;
};

// Android pulls the icon label from `<string name="app_name">…</string>`.
// The default value goes into `values/strings.xml` (already managed by
// Expo's name field) and per-locale overrides go into `values-<lang>/`.
const withAndroidLocalizedName = (config, NAMES) => {
  // Make sure the default `app_name` matches what we want (in case the
  // user's app.config.ts default drifts from NAMES.default).
  config = withStringsXml(config, (cfg) => {
    cfg.modResults = AndroidConfig.Strings.setStringItem(
      [{ $: { name: 'app_name', translatable: 'false' }, _: NAMES.default }],
      cfg.modResults,
    );
    return cfg;
  });

  // Write `app/src/main/res/values-<lang>/strings.xml` for every non-default
  // locale. Android picks these up automatically based on the device's
  // configured language.
  config = withDangerousMod(config, [
    'android',
    async (cfg) => {
      const projectRoot = cfg.modRequest.platformProjectRoot;
      const resDir = path.join(projectRoot, 'app', 'src', 'main', 'res');
      for (const locale of SUPPORTED_LOCALES) {
        if (locale === 'en') continue; // English is the default values/ already.
        const valuesDir = path.join(resDir, `values-${locale}`);
        fs.mkdirSync(valuesDir, { recursive: true });
        const filePath = path.join(valuesDir, 'strings.xml');
        const escaped = NAMES[locale]
          .replaceAll('&', '&amp;')
          .replaceAll('<', '&lt;')
          .replaceAll('"', '&quot;');
        const content =
          `<?xml version="1.0" encoding="utf-8"?>\n` +
          `<resources>\n` +
          `  <string name="app_name" translatable="false">${escaped}</string>\n` +
          `</resources>\n`;
        fs.writeFileSync(filePath, content, 'utf8');
      }
      return cfg;
    },
  ]);

  return config;
};

module.exports = function withLocalizedAppName(config, options) {
  const NAMES = resolveNames(config, options);
  // { en: { NSPhotoLibraryUsageDescription: '…' }, ar: { … } }
  const USAGE = (options && options.iosUsage) || {};
  config = withIosLocalizedName(config, NAMES, USAGE);
  config = withAndroidLocalizedName(config, NAMES);
  return config;
};
